#!/usr/bin/env python3
"""Step 1b: a Verilog module, for one format (W, P), that computes the whole output of roundRawFNToRecFN
(recoded result, a care mask of the bits the documentation fixes, the five flags) from:
  - the integer formulas of stage 3 (expstage.py's model, proved IEEE-correct for every format by z3);
  - the rounding datapath given by the DEFINITION (ref_round.bv, emitted by bv2v.py; stage 2 proves it equal
    to HardFloat's lines 174-218 for every width);
  - the fraction field written as "the p-1 bits of the rounded significand below its top bit" (H2);
  - the special inputs as the documentation states them (H3): invalidExc -> default NaN, flag invalid;
    infiniteExc -> infinity of in_sign, flag infinite; isNaN -> default NaN; isInf -> infinity; isZero -> zero.
The recoded encodings follow the doc 5.2 table; x bits are left out of `care`.
Output `valid`: the documented domain (valid mode; not both exception inputs; a finite nonzero input has
sig top bits != 00). usage: spec_gen.py W P OUT.v
"""
import sys


def gen(W, P):
    B = 1 << (W - 1)
    L = []
    A = L.append
    A("// spec for roundRawFNToRecFN#(%d, %d), generated by spec_gen.py" % (W, P))
    A("module spec(input control, input invalidExc, input infiniteExc, input in_isNaN, input in_isInf,")
    A("            input in_isZero, input in_sign, input [%d:0] in_sExp, input [%d:0] in_sig," % (W + 1, P + 2))
    A("            input [2:0] roundingMode, output [%d:0] out, output [%d:0] care, output [4:0] flags," % (W + P, W + P))
    A("            output valid);")
    A("  localparam integer B = %d, P = %d;" % (B, P))
    A("  wire d = in_sig[%d];" % (P + 2))
    A("  wire signed [39:0] s = {{%d{in_sExp[%d]}}, in_sExp};" % (40 - (W + 2), W + 1))
    A("  wire signed [39:0] u = (s >= 0) ? s : s + 4 * B;")
    A("  wire signed [39:0] k0 = B + 2 - u;")
    A("  wire signed [39:0] k = (k0 < 0) ? 0 : ((k0 > P + 1) ? P + 1 : k0);")
    A("  wire signed [39:0] dd = {39'd0, d};")
    A("  wire signed [39:0] RHF = 2 + ((dd > k) ? dd : k);")
    A("  wire [%d:0] one = 1;" % (P + 3))
    A("  wire [%d:0] m4 = (one << RHF[15:0]) - 1;" % (P + 3))
    A("  wire [%d:0] mask = m4[%d:0];" % (P + 2, P + 2))
    A("  wire ne = roundingMode == 3'b000, na = roundingMode == 3'b100, odd = roundingMode == 3'b110;")
    A("  wire magUp = (roundingMode == 3'b010 && in_sign) || (roundingMode == 3'b011 && !in_sign);")
    A("  wire [%d:0] rs; wire rpb, ext, anyRound, dvalid;" % (P + 3))
    A("  ref_dp dp(.sig(in_sig), .mask(mask), .m2(roundingMode[2]), .m1(roundingMode[1]), .m0(roundingMode[0]),")
    A("            .sign(in_sign), .roundedSig(rs), .roundPosBit(rpb), .anyRoundExtra(ext), .anyRound(anyRound),")
    A("            .valid(dvalid));")
    A("  wire signed [39:0] t = {38'd0, rs[%d:%d]};" % (P + 1, P))
    A("  wire signed [39:0] sRE = s + t;")
    A("  wire ovf = sRE >= 3 * B;")
    A("  wire tu = sRE <= B + 3 - P;")
    A("  wire tiny1 = RHF > 2 + dd, tiny2 = RHF > 3 + dd;")
    A("  wire carryHF = d ? rs[%d] : rs[%d];          // bit m+1 of y" % (P + 1, P))
    A("  wire ub_rpb = d ? in_sig[2] : in_sig[1];")
    A("  wire ub_any = d ? |in_sig[2:0] : |in_sig[1:0];")
    A("  wire unbIncr = ((ne || na) && ub_rpb) || (magUp && ub_any);")
    A("  wire uf = tu || (anyRound && (s < 2 * B) && tiny1 && !(control && !tiny2 && carryHF && rpb && unbIncr));")
    A("  wire ix = ovf || tu || anyRound;")
    A("  // fraction: the P-1 bits of the rounded significand just below its top bit (top at index P-1+t)")
    A("  wire [%d:0] rst = rs >> t[1:0];" % (P + 3))
    A("  wire [%d:0] fracFin = rst[%d:0];" % (P - 2, P - 2))
    A("  wire [%d:0] expFin = sRE[%d:0];" % (W, W))
    A("  localparam [%d:0] FM = {%d{1'b1}};" % (P - 2, P - 1))
    A("  localparam [%d:0] TOP3 = 3'b111 << %d;" % (W, W - 2))
    A("  localparam [%d:0] EINF = 3'b110 << %d, ENAN = 3'b111 << %d;" % (W, W - 2, W - 2))
    A("  localparam [%d:0] EMAXF = %d, EMINS = %d;" % (W, 3 * B - 1, B + 3 - P))
    A("  localparam [%d:0] FNAN = 1 << %d;" % (P - 2, P - 2))
    A("  reg osign; reg [%d:0] oexp, cexp; reg [%d:0] ofr, cfr; reg [4:0] fl;" % (W, P - 2))
    A("  always @* begin")
    A("    osign = in_sign; cexp = TOP3; cfr = FM; fl = 5'b0;")
    A("    if (invalidExc || (!infiniteExc && in_isNaN)) begin osign = 1'b0; oexp = ENAN; ofr = FNAN;")
    A("      fl = invalidExc ? 5'b10000 : 5'b0; end")
    A("    else if (infiniteExc || in_isInf) begin oexp = EINF; ofr = 0; cfr = 0; fl = infiniteExc ? 5'b01000 : 5'b0; end")
    A("    else if (in_isZero) begin oexp = 0; ofr = 0; end")
    A("    else begin")
    A("      fl = {2'b00, ovf, uf, ix};")
    A("      if (ovf && (ne || na || magUp)) begin oexp = EINF; ofr = 0; cfr = 0; end")
    A("      else if (ovf) begin oexp = EMAXF; ofr = FM; cexp = {%d{1'b1}}; end" % (W + 1))
    A("      else if (tu && (magUp || odd)) begin oexp = EMINS; ofr = 0; cexp = {%d{1'b1}}; end" % (W + 1))
    A("      else if (tu) begin oexp = 0; ofr = 0; end")
    A("      else begin oexp = expFin; ofr = fracFin; cexp = {%d{1'b1}}; end" % (W + 1))
    A("    end")
    A("  end")
    A("  assign out = {osign, oexp, ofr};")
    A("  assign care = {1'b1, cexp, cfr};")
    A("  assign flags = fl;")
    A("  wire special = invalidExc || infiniteExc || in_isNaN || in_isInf || in_isZero;")
    A("  assign valid = !(invalidExc && infiniteExc) && roundingMode != 3'b101 && roundingMode != 3'b111")
    A("                 && (special || in_sig[%d:%d] != 2'b00);" % (P + 2, P + 1))
    A("endmodule")
    return "\n".join(L) + "\n"


def top(W, P):
    return """module top(input control, input invalidExc, input infiniteExc, input in_isNaN, input in_isInf,
           input in_isZero, input in_sign, input [%d:0] in_sExp, input [%d:0] in_sig, input [2:0] roundingMode,
           output bad);
  wire [%d:0] o, so, care; wire [4:0] f, sf; wire valid;
  roundRawFNToRecFN #(%d, %d) hf(control, invalidExc, infiniteExc, in_isNaN, in_isInf, in_isZero, in_sign,
                               in_sExp, in_sig, roundingMode, o, f);
  spec sp(control, invalidExc, infiniteExc, in_isNaN, in_isInf, in_isZero, in_sign, in_sExp, in_sig,
          roundingMode, so, care, sf, valid);
  assign bad = valid && ((((o ^ so) & care) != 0) || (f != sf));
endmodule
""" % (W + 1, P + 2, W + P, W, P)


def main():
    W, P = int(sys.argv[1]), int(sys.argv[2])
    open(sys.argv[3], "w").write(gen(W, P) + "\n" + top(W, P))


if __name__ == "__main__":
    main()
