"""Writes vectors/vectors.txt.  Expected values come from zlib.crc32 (the C zlib library), not from this package.

Each line:  NAME  LENGTH  MESSAGE_HEX  CRC32
    MESSAGE_HEX  the bytes in wire order (for a frame: destination address .. last data or pad byte, no FCS)
    CRC32        zlib.crc32(message) as 8 hex digits.  The Ethernet FCS is these 4 bytes least significant
                 byte first, appended after the message.
"""
import random
import struct
import zlib
from pathlib import Path


def mac(s):
    return bytes(int(x, 16) for x in s.split(":"))


def frame(dst, src, ethertype, payload):
    f = mac(dst) + mac(src) + struct.pack(">H", ethertype) + payload
    return f + bytes(max(0, 60 - len(f)))                      # pad to the 60-byte minimum before the FCS


def udp_ipv4(src_ip, dst_ip, sport, dport, data):
    udp = struct.pack(">HHHH", sport, dport, 8 + len(data), 0) + data
    hdr = struct.pack(">BBHHHBBH4s4s", 0x45, 0, 20 + len(udp), 1, 0x4000, 64, 17, 0, bytes(src_ip), bytes(dst_ip))
    s = sum(struct.unpack(">10H", hdr))
    s = (s & 0xFFFF) + (s >> 16)
    s = (s & 0xFFFF) + (s >> 16)
    hdr = hdr[:10] + struct.pack(">H", ~s & 0xFFFF) + hdr[12:]
    return hdr + udp


V = []
V.append(("check_123456789", b"123456789"))
V.append(("empty", b""))
V.append(("one_00", b"\x00"))
V.append(("one_ff", b"\xff"))
V.append(("zeros_4", bytes(4)))
V.append(("ones_4", b"\xff" * 4))
V.append(("ascii_alphabet", b"abcdefghijklmnopqrstuvwxyz"))
arp = struct.pack(">HHBBH", 1, 0x0800, 6, 4, 1) + mac("02:00:00:00:00:01") + bytes([192, 168, 1, 10]) + bytes(6) + bytes([192, 168, 1, 1])
V.append(("eth_arp_request_60", frame("ff:ff:ff:ff:ff:ff", "02:00:00:00:00:01", 0x0806, arp)))
V.append(("eth_udp_min_60", frame("02:00:00:00:00:02", "02:00:00:00:00:01", 0x0800,
                                  udp_ipv4([10, 0, 0, 1], [10, 0, 0, 2], 5000, 5001, b"colony"))))
V.append(("eth_vlan_udp_64", frame("02:00:00:00:00:02", "02:00:00:00:00:01", 0x8100,
                                   struct.pack(">HH", 0x0064, 0x0800) + udp_ipv4([10, 0, 0, 1], [10, 0, 0, 2], 5000, 5001, bytes(range(18))))))
V.append(("eth_multicast_udp_100", frame("03:00:00:00:00:2a", "02:00:00:00:00:01", 0x0800,
                                         udp_ipv4([10, 1, 33, 1], [224, 224, 0, 42], 20000, 20001, bytes((7 * i) & 0xFF for i in range(58))))))
V.append(("eth_max_1514", frame("02:00:00:00:00:02", "02:00:00:00:00:01", 0x0800,
                                udp_ipv4([10, 0, 0, 1], [10, 0, 0, 2], 5000, 5001, bytes(i & 0xFF for i in range(1472))))))
V.append(("eth_jumbo_9014", frame("02:00:00:00:00:02", "02:00:00:00:00:01", 0x0800,
                                  udp_ipv4([10, 0, 0, 1], [10, 0, 0, 2], 5000, 5001, bytes((i * 31 + 7) & 0xFF for i in range(8972))))))
rng = random.Random(802)
for n in range(60, 68):                                        # every value of length mod 8
    V.append(("eth_random_%d" % n, frame("02:00:00:00:00:02", "02:00:00:00:00:01", 0x88B5, bytes(rng.randrange(256) for _ in range(n - 14)))))
for i in range(32):
    n = rng.randrange(1, 300)
    V.append(("random_%02d_%d" % (i, n), bytes(rng.randrange(256) for _ in range(n))))

out = ["# CRC-32/ISO-HDLC (IEEE 802.3 FCS) known-answer vectors.  Generated by vectors/make_vectors.py.",
       "# Expected values: zlib.crc32, zlib %s.  Ethernet FCS = CRC32 bytes, least significant first." % zlib.ZLIB_RUNTIME_VERSION,
       "# NAME LENGTH MESSAGE_HEX CRC32   (MESSAGE_HEX is '-' for the empty message)"]
for name, m in V:
    out.append("%s %d %s %08x" % (name, len(m), m.hex() or "-", zlib.crc32(m)))
assert zlib.crc32(b"123456789") == 0xCBF43926
Path(__file__).with_name("vectors.txt").write_text("\n".join(out) + "\n")
print("%d vectors, %d bytes" % (len(V), sum(len(m) for _, m in V)))
