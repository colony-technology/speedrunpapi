"""Generate the two integer tables of the exact model: tables/exp.txt and tables/gelu.txt.

exp:  E[k] = round(2^24 * exp(-k / 256))                     for k = 0 .. 6144   (the grid 0 .. 24 in steps of 2^-8)
gelu: G[k] = round(2^16 * x * Phi(x)),  x = -8 + k / 256      for k = 0 .. 4096   (the grid -8 .. 8 in steps of 2^-8)
      Phi(x) = (1 + erf(x / sqrt 2)) / 2

round is to the nearest integer. Each value is computed with mpmath at 60 significant digits and again at 100; the
two must give the same integer, and the exact value must be further than 10^-30 from a half-integer, so the rounding
cannot depend on the precision. (A tie is impossible anyway: exp and erf at nonzero rational points are
irrational; the distance check makes the claim measurable.)

usage: python make_tables.py            write the tables
       python make_tables.py --check    regenerate and compare with the files in tables/
"""
import os
import sys

import mpmath

HERE = os.path.dirname(os.path.abspath(__file__))
EXP_N = 24 * 256          # last grid point 24
GELU_N = 16 * 256         # grid -8 .. 8


def exp_value(k, dps):
    with mpmath.workdps(dps):
        return mpmath.mpf(2) ** 24 * mpmath.exp(-mpmath.mpf(k) / 256)


def gelu_value(k, dps):
    with mpmath.workdps(dps):
        x = mpmath.mpf(-8) + mpmath.mpf(k) / 256
        return mpmath.mpf(2) ** 16 * x * (1 + mpmath.erf(x / mpmath.sqrt(2))) / 2


def rounded(f, k):
    lo, hi = f(k, 60), f(k, 100)
    a, b = int(mpmath.nint(lo)), int(mpmath.nint(hi))
    assert a == b, (f.__name__, k)
    with mpmath.workdps(100):
        frac = hi - mpmath.floor(hi)
        assert abs(frac - mpmath.mpf(1) / 2) > mpmath.mpf(10) ** -30, (f.__name__, k)
    return a


def build():
    exp = [rounded(exp_value, k) for k in range(EXP_N + 1)]
    gelu = [rounded(gelu_value, k) for k in range(GELU_N + 1)]
    assert exp[0] == 1 << 24 and exp[-1] == 0
    assert gelu[0] == 0 and gelu[-1] == 8 << 16 and gelu[GELU_N // 2] == 0
    return exp, gelu


def text(name, rule, values):
    return "# %s\n# %s\n# %d values, one per line, generated by make_tables.py\n%s\n" % (
        name, rule, len(values), "\n".join(str(v) for v in values))


def main():
    exp, gelu = build()
    files = {
        "exp.txt": text("exp table", "E[k] = round(2^24 * exp(-k/256)), k = 0 .. %d" % EXP_N, exp),
        "gelu.txt": text("gelu table", "G[k] = round(2^16 * x * Phi(x)), x = -8 + k/256, k = 0 .. %d" % GELU_N, gelu),
    }
    os.makedirs(os.path.join(HERE, "tables"), exist_ok=True)
    for name, body in files.items():
        path = os.path.join(HERE, "tables", name)
        if "--check" in sys.argv:
            assert open(path).read() == body, name + " differs from its generator"
            print("tables/%s: equal to its generator" % name)
        else:
            open(path, "w").write(body)
            print("wrote tables/%s" % name)


if __name__ == "__main__":
    main()
